/** 生日卡内置祝贺语：按元素提供，另有一组通用 */
export const GREETINGS = {
  通用: [
    '愿星辰为你引路，愿旅途常有惊喜。',
    '又一年风起，愿你如愿以偿。',
    '把今天留给值得的人与事。',
    '生日快乐，愿此后的每一步都轻快。',
    '提瓦特的今天，因你而多一分热闹。',
  ],
  火: ['愿这份热意不被风雨吹熄。', '燃烧得再亮一些，今天由你照亮。'],
  水: ['愿心绪如静水，照见想要的答案。', '让流水带走疲惫，留下清亮。'],
  冰: ['愿你的锋芒始终清澈。', '冰雪之下，亦有温热的祝愿。'],
  雷: ['愿你的每一次决断都干脆利落。', '雷光照亮的地方，都有你的名字。'],
  草: ['愿新芽与好消息一同生长。', '愿你被这片土地温柔以待。'],
  风: ['愿风把自由与歌一同送到你身边。', '愿你的旅途永远有风相伴。'],
  岩: ['愿你所立之处，皆是坦途。', '如磐石般安定，也如金石般明亮。'],
}

export function pickGreeting(element, seed = Date.now()) {
  const pool = [...(GREETINGS[element] || []), ...GREETINGS.通用]
  const i = Math.abs(Number(seed) || 0) % pool.length
  return pool[i]
}
