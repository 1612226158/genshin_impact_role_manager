#!/usr/bin/env node
import { mkdirSync } from 'node:fs'
import { BASE, OUT_DIR, launchBrowser, openRoute, sleep, startVite, waitAssets, waitServer } from './lib/common.mjs'
const server = startVite()
let browser, failed = 0
const check = (name, ok) => { console.log(`${ok ? 'PASS' : 'FAIL'} ${name}`); if (!ok) failed++ }
try {
  if (!await waitServer(BASE)) throw new Error('server not ready')
  browser = await launchBrowser()
  const page = await browser.newPage()
  page.on('pageerror', e => { console.log(e.message); failed++ })
  mkdirSync(OUT_DIR, { recursive: true })
  await openRoute(page, BASE, '/')
  check('library sort uses themed selector', await page.$('[role="combobox"][aria-label="排序方式"]') !== null && await page.$('select') === null)
  const heights = () => page.$$eval('.head-extra > .gs-btn, .head-extra .select-trigger, .head-extra .dir, .head-extra .search', els => els.map(el => el.getBoundingClientRect().height))
  check('library controls have the same height', (await heights()).every(h => Math.abs(h - 36) < 1))
  check('element badge is circular and centered', await page.$eval('.card .badge', el => {
    const r = el.getBoundingClientRect(), icon = el.querySelector('.el').getBoundingClientRect()
    return r.width === r.height && Math.abs((r.left + r.width / 2) - (icon.left + icon.width / 2)) < 1 && Math.abs((r.top + r.height / 2) - (icon.top + icon.height / 2)) < 1
  }))
  await page.evaluate(() => [...document.querySelectorAll('.chip-row')].find(e => e.textContent.includes('元素')).querySelectorAll('button')[1].click())
  await sleep(80)
  check('filtering animates card removal and movement', await page.$$eval('.cell', els => els.some(el => el.getAnimations().length > 0)))
  await sleep(600)
  check('clear-filter control matches toolbar height', (await heights()).every(h => Math.abs(h - 36) < 1))
  await page.evaluate(() => [...document.querySelectorAll('.head-extra button')].find(b => b.textContent.includes('清除筛选')).click())
  await sleep(600)
  await page.click('[aria-label="排序方式"]')
  await page.evaluate(() => [...document.querySelectorAll('[role="option"]')].find(el => el.textContent.replace('✓', '').trim() === '名称').click())
  await sleep(100)
  check('sorting animates existing card positions', await page.$$eval('.cell', els => els.some(el => el.getAnimations().length > 0)))
  await sleep(500)
  await page.screenshot({ path: `${OUT_DIR}/character-library-controls.png` })
  await page.evaluate(() => [...document.querySelectorAll('.head-extra button')].find(b => b.textContent.includes('新建角色')).click())
  await page.waitForFunction(() => Boolean(document.querySelector('dialog[open]')))
  check('new character opens a modal without leaving library', await page.evaluate(() => location.pathname === '/' && document.querySelector('dialog').matches(':modal')))
  await page.click('dialog .head-ops button:first-of-type')
  await page.waitForFunction(() => !document.querySelector('dialog'))
  await openRoute(page, BASE, '/c/1055')
  await waitAssets(page)
  const fits = () => page.evaluate(() => {
    const box = document.querySelector('.flip-inner').getBoundingClientRect()
    return [...document.querySelectorAll('.flip-face img')].every(img => {
      const r = img.getBoundingClientRect()
      return r.left >= box.left - 1 && r.right <= box.right + 1 && r.top >= box.top - 1 && r.bottom <= box.bottom + 1 &&
        Math.abs(r.width / r.height - img.naturalWidth / img.naturalHeight) < .01
    })
  })
  const beforeFlip = await page.$eval('.flip-artwork', el => [el.clientWidth, el.clientHeight])
  check('both artwork faces fit the stage without distortion', await fits())
  await page.click('.flip-artwork')
  await sleep(100)
  check('artwork flip has a real 3D animation', await page.$eval('.flip-inner', el => getComputedStyle(el).transform !== 'none' && el.getAnimations().length > 0))
  await sleep(650)
  check('flipping keeps stage dimensions stable', await page.$eval('.flip-artwork', (el, size) => el.clientWidth === size[0] && el.clientHeight === size[1], beforeFlip))
  check('flipped face uses avatar_hd', await page.$eval('.back-face img', el => /_hd\.webp/.test(el.src)))
  await page.click('.flip-artwork')
  await sleep(700)
  check('second click flips back to poster', await page.$eval('.flip-artwork', el => el.getAttribute('aria-pressed') === 'false'))
  await page.click('.tabs button:nth-child(2)')
  await sleep(700)
  check('artwork fits the narrow story layout', await fits())
  await page.click('.tabs button:first-child')
  await sleep(700)
  const edit = async () => {
    await page.evaluate(() => document.querySelector('.detail-edit').click())
    await page.waitForFunction(() => Boolean(document.querySelector('dialog[open]')))
  }
  await edit()
  check('edit stays on detail route', await page.evaluate(() => location.pathname === '/c/1055'))
  check('modal includes floating painting layers', await page.$$eval('.painting-stack img', els => els.length > 0 && getComputedStyle(els[0]).transform !== 'none'))
  check('modal locks page scroll', await page.evaluate(() => document.body.style.overflow === 'hidden'))
  await page.screenshot({ path: `${OUT_DIR}/character-editor-modal.png` })
  const changeTitle = () => page.evaluate(() => {
    const input = [...document.querySelectorAll('dialog input')].find(el => el.value === '无害甜度')
    input.value = '无害甜度·弹窗测试'; input.dispatchEvent(new Event('input', { bubbles: true }))
  })
  await changeTitle()
  await page.keyboard.press('Escape')
  await sleep(100)
  check('escape asks before discarding dirty edits', await page.$('dialog .mask .panel') !== null)
  await page.evaluate(() => [...document.querySelectorAll('dialog .mask button')].find(b => b.textContent.includes('取消')).click())
  await sleep(250)
  check('canceling discard keeps modal and scroll lock', await page.evaluate(() => Boolean(document.querySelector('dialog[open]')) && document.body.style.overflow === 'hidden'))
  await page.evaluate(() => [...document.querySelectorAll('dialog .head-ops button')].find(b => b.textContent.trim() === '保存').click())
  await page.waitForFunction(() => !document.querySelector('dialog'))
  check('save closes modal and updates current detail', await page.evaluate(() => location.pathname === '/c/1055' && document.querySelector('.side .title').textContent.includes('弹窗测试')))
  check('closing modal unlocks scroll and restores edit focus', await page.evaluate(() => document.body.style.overflow !== 'hidden' && document.activeElement.textContent.trim() === '编辑'))
  await edit()
  await page.evaluate(() => {
    const input = document.querySelector('dialog input'); input.value += '改'; input.dispatchEvent(new Event('input', { bubbles: true }))
  })
  await page.keyboard.press('Escape'); await sleep(80)
  await page.evaluate(() => [...document.querySelectorAll('dialog .mask button')].find(b => b.textContent.includes('放弃')).click())
  await page.waitForFunction(() => !document.querySelector('dialog'))
  check('discard leaves saved character name unchanged', await page.$eval('.name-row h1', el => el.textContent === '砂糖'))
  await page.setViewport({ width: 390, height: 844 })
  await sleep(200)
  check('mobile artwork remains inside its stage', await fits())
  await edit()
  await sleep(200)
  check('mobile modal fits viewport', await page.$eval('dialog', el => {
    const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight
  }))
  check('mobile modal body can scroll', await page.$eval('dialog .form', el => el.scrollHeight > el.clientHeight))
  await page.screenshot({ path: `${OUT_DIR}/character-editor-mobile.png` })
  await page.keyboard.press('Escape')
  await page.waitForFunction(() => !document.querySelector('dialog'))
  await page.evaluate(() => document.documentElement.classList.add('no-motion'))
  await page.click('.flip-artwork')
  await sleep(30)
  check('flip respects motion-off setting', await page.$eval('.flip-inner', el => parseFloat(getComputedStyle(el).transitionDuration) < .001))
  await openRoute(page, BASE, '/c/1055/edit')
  check('legacy edit URL no longer shows a separate editor page', await page.evaluate(() => location.pathname === '/c/1055' && !document.querySelector('.page .form')))
} finally { await browser?.close(); server.kill(); await sleep(300) }
console.log(failed ? `${failed} failures` : 'All character UI checks passed')
process.exitCode = failed ? 1 : 0
